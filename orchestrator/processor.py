"""
This file defines the VirtualProcessor class, which executes the AST generated by the Parser.
It manages the runtime state (variables), interacts with instruments via the context, and handles control flow.
"""
import logging
import ast
import numpy as np
from .instrument_client import InstrumentError
from .parser import Lexer, Parser

class VirtualProcessor:
    def __init__(self, context):
        """
        Initialize the VirtualProcessor with a context.
        Context should contain:
        - 'instruments': InstrumentClient instance
        - 'sleep': sleep function
        - 'save_data': data saving function
        """
        self.context = context
        self.vars = {}   # name -> value (includes params)
        self.data_schema = None # { 'param_axes': [], 'num_data': N }
        self.param_defaults = {}
        
        # Dedicated engine logger; output is routed by Django LOGGING to logs/engine.log
        self.logger = logging.getLogger("quail.engine.processor")

    @staticmethod
    def _coerce_numeric_strings(obj):
        """Recursively convert numeric strings to numbers."""
        if isinstance(obj, str):
            s = obj.strip()
            # int
            if s and (s.isdigit() or (s[0] in "+-" and s[1:].isdigit())):
                try:
                    return int(s)
                except Exception:
                    return obj
            # float
            try:
                # Avoid converting non-numeric text like 'abc'
                if any(ch.isdigit() for ch in s):
                    return float(s)
            except Exception:
                pass
            return obj
        if isinstance(obj, list):
            return [VirtualProcessor._coerce_numeric_strings(v) for v in obj]
        if isinstance(obj, tuple):
            return [VirtualProcessor._coerce_numeric_strings(v) for v in obj]
        return obj

    @staticmethod
    def _is_number(v):
        return isinstance(v, (int, float, np.integer, np.floating)) and not isinstance(v, bool)

    @staticmethod
    def _drop_empty_rows(rows):
        return [row for row in rows if len(row) > 0]

    @staticmethod
    def _normalize_axis_names(raw_axes, field_name, allow_placeholder=False):
        if not isinstance(raw_axes, (list, tuple)):
            raise Exception(f"'{field_name}' argument in init_data must be a tuple of strings")
        axes = []
        for i, item in enumerate(raw_axes):
            if not isinstance(item, str):
                raise Exception(f"'{field_name}' axis at index {i} must be a string")
            name = item.strip()
            if not name:
                raise Exception(f"'{field_name}' axis at index {i} cannot be empty")
            if name == '_' and not allow_placeholder:
                raise Exception(f"'_' placeholder is only allowed in '{field_name}' axes")
            axes.append(name)
        return axes

    def _normalize_run_data(self, data):
        """
        Normalize FPGA output to an N x 4 numeric table when possible.
        """
        if data is None:
            return []

        # Some instrumentserver/proxy paths return a stringified list.
        if isinstance(data, str):
            text = data.strip()
            if text:
                try:
                    data = ast.literal_eval(text)
                except Exception:
                    return data

        # Convert numpy-like payloads early.
        if isinstance(data, np.ndarray):
            data = data.tolist()

        if not isinstance(data, (list, tuple)):
            return data

        data = self._coerce_numeric_strings(data)
        if not isinstance(data, (list, tuple)):
            return data

        # If this is 2D array-like payload from sequencer, coerce to N x 4.
        if data and all(isinstance(row, (list, tuple)) for row in data):
            rows = self._drop_empty_rows([list(row) for row in data])
            if all(all(self._is_number(v) for v in row) for row in rows):
                # Respect declared schema rows if available.
                schema_rows = None
                if isinstance(self.data_schema, dict):
                    v = self.data_schema.get('num_data')
                    if isinstance(v, (int, np.integer)) and int(v) >= 0:
                        schema_rows = int(v)
                if schema_rows is not None and len(rows) > 0:
                    if len(rows) == schema_rows:
                        return rows
                    if len(rows) > schema_rows and all(len(r) == len(rows[0]) for r in rows):
                        return rows[:schema_rows]
                    if all(len(r) == len(rows[0]) for r in rows) and len(rows[0]) == schema_rows:
                        return [list(col) for col in zip(*rows)]
                # No schema yet: preserve row-major payload as provided.
                if all(len(row) == len(rows[0]) for row in rows):
                    return rows
                return rows

        # 1D list-like payload
        if all(self._is_number(v) for v in data):
            return list(data)

        return data

    def _normalize_save_data(self, data):
        """
        Normalize save() payload to row-major list-of-lists (R x N).
        A single numeric array becomes 1 x N.
        """
        if isinstance(data, np.ndarray):
            data = data.tolist()
        if data is None:
            return [[]]
        if isinstance(data, str):
            text = data.strip()
            if text:
                try:
                    data = ast.literal_eval(text)
                except Exception:
                    raise Exception("save() 'data' string is not a valid array literal")
            else:
                return [[]]
        data = self._coerce_numeric_strings(data)

        if isinstance(data, (list, tuple)):
            if len(data) == 0:
                return [[]]
            # 1D numeric -> 1xN
            if all(self._is_number(v) for v in data):
                return [list(data)]
            # 2D numeric -> RxN
            if all(isinstance(row, (list, tuple)) for row in data):
                rows = self._drop_empty_rows([list(row) for row in data])
                if all(all(self._is_number(v) for v in row) for row in rows):
                    schema_rows = None
                    if isinstance(self.data_schema, dict):
                        v = self.data_schema.get('num_data')
                        if isinstance(v, (int, np.integer)) and int(v) >= 0:
                            schema_rows = int(v)
                    if schema_rows is not None and len(rows) > schema_rows and all(len(r) == len(rows[0]) for r in rows):
                        return rows[:schema_rows]
                    return rows
            raise Exception("save() 'data' must be a numeric array")

        if self._is_number(data):
            return [[data]]
        raise Exception("save() 'data' must be a numeric array")

    @staticmethod
    def _is_scan_object(value):
        return isinstance(value, dict) and value.get("ty") in {"NoScan", "RangeScan", "CenterScan", "ExplicitScan"}

    @staticmethod
    def _scan_object(name, args, kwargs):
        out = {"ty": name}
        if name == "NoScan":
            out["value"] = kwargs.get("value", args[0] if args else 0)
            if "repetitions" in kwargs:
                out["repetitions"] = kwargs["repetitions"]
            return out
        if name == "RangeScan":
            for idx, key in enumerate(("start", "stop", "npoints")):
                if key in kwargs:
                    out[key] = kwargs[key]
                elif idx < len(args):
                    out[key] = args[idx]
            if "randomize" in kwargs:
                out["randomize"] = kwargs["randomize"]
            if "seed" in kwargs:
                out["seed"] = kwargs["seed"]
            return out
        if name == "CenterScan":
            for idx, key in enumerate(("center", "span", "step")):
                if key in kwargs:
                    out[key] = kwargs[key]
                elif idx < len(args):
                    out[key] = args[idx]
            if "randomize" in kwargs:
                out["randomize"] = kwargs["randomize"]
            if "seed" in kwargs:
                out["seed"] = kwargs["seed"]
            return out
        if name == "ExplicitScan":
            seq = kwargs.get("sequence", args[0] if args else [])
            out["sequence"] = list(seq) if isinstance(seq, (list, tuple)) else []
            return out
        return out

    @staticmethod
    def _scan_values(scan):
        if not isinstance(scan, dict):
            if isinstance(scan, (list, tuple)):
                return list(scan)
            return [scan]
        ty = scan.get("ty")
        if ty == "NoScan":
            reps = int(scan.get("repetitions") or 1)
            return [scan.get("value")] * max(1, reps)
        if ty == "RangeScan":
            start = float(scan.get("start", 0.0))
            stop = float(scan.get("stop", start))
            npoints = max(1, int(scan.get("npoints", 1)))
            vals = np.linspace(start, stop, npoints).tolist()
        elif ty == "CenterScan":
            center = float(scan.get("center", 0.0))
            span = float(scan.get("span", 0.0))
            step = float(scan.get("step", 1.0))
            if step == 0:
                raise ValueError("CenterScan step cannot be 0")
            start = center - span / 2.0
            stop = center + span / 2.0
            vals = np.arange(start, stop + abs(step) / 1000.0, abs(step)).tolist()
        elif ty == "ExplicitScan":
            vals = list(scan.get("sequence") or [])
        else:
            vals = [scan]
        if scan.get("randomize") and len(vals) > 1:
            rng = np.random.default_rng(scan.get("seed", None))
            vals = list(rng.permutation(vals))
        return vals

    @staticmethod
    def _coerce_scan_to_declared_type(value, default):
        if not VirtualProcessor._is_scan_object(value):
            raise ValueError("expected a scan object")
        if not VirtualProcessor._is_scan_object(default):
            return value
        declared_ty = default.get("ty")
        if value.get("ty") == declared_ty:
            return value
        coerced = {"ty": declared_ty}
        for key, fallback in default.items():
            if key == "ty":
                continue
            coerced[key] = value.get(key, fallback)
        return coerced

    def parse(self, code):
        """
        Parse the given code into an AST.
        """
        lexer = Lexer(code)
        parser = Parser(lexer)
        ast = parser.program()
        self.logger.info("Parsed script into AST with %d top-level statements", len(ast))
        return ast

    def execute(self, code):
        """
        Parse and execute the given code.
        """
        self.logger.info("VirtualProcessor starting execution")
        ast = self.parse(code)
        self.start_proc(ast)
        self.logger.info("VirtualProcessor finished execution")

    def evaluate(self, node):
        """
        Evaluate an AST node (expression).
        Handles literals, variables, GET commands, tuples, and binary operations.
        """
        if isinstance(node, (int, float, str)):
            return node
        
        if isinstance(node, dict):
            if node['type'] == 'VAR':
                # Return value if it exists (local var), else return the name itself (potential param name)
                if node['name'] in self.vars:
                    return self.vars[node['name']]
                return self.context.get(node['name'], node['name'])
            elif node['type'] == 'GET':
                target_name = node['target']
                # If target is a local var, get its value (which might be a param name)
                # If not, use the target name directly
                path = self.vars.get(target_name, target_name)
                
                # Try to get parameter
                # We assume path is "instrument.parameter"
                if isinstance(path, str):
                    parts = path.split('.')
                    if len(parts) >= 2:
                        inst = parts[0]
                        param = '.'.join(parts[1:])
                        val = self.context['instruments'].get_parameter(inst, param)
                        self.logger.info(f"Got {path} = {val}")
                        return val
                    else:
                        # Parameter without instrument is not valid, placeholder for potential future feature
                        raise ValueError("Invalid parameter name, expected instrument.parameter")
                return 0 # Fallback
            elif node['type'] == 'TUPLE':
                # Evaluate all items in tuple
                return tuple(self.evaluate(item) for item in node['items'])
            elif node['type'] == 'BINOP':
                left = self.evaluate(node['left'])
                right = self.evaluate(node['right'])
                op = node['op']
                if op == 'EQ': return left == right
                elif op == 'NEQ': return left != right
                elif op == 'LT': return left < right
                elif op == 'LTE': return left <= right
                elif op == 'GT': return left > right
                elif op == 'GTE': return left >= right
            elif node['type'] == 'CALL':
                name = node.get('name')
                args = [self.evaluate(item) for item in node.get('args', [])]
                kwargs = {k: self.evaluate(v) for k, v in (node.get('kwargs') or {}).items()}
                if name in {"NoScan", "RangeScan", "CenterScan", "ExplicitScan"}:
                    return self._scan_object(name, args, kwargs)
                raise ValueError(f"Unsupported function call: {name}")
        return node

    def evaluate_param_value(self, node):
        if isinstance(node, dict) and node.get('type') == 'VAR':
            name = node.get('name')
            return self.vars[name] if name in self.vars else str(name)
        if isinstance(node, dict) and node.get('type') == 'TUPLE':
            return tuple(self.evaluate_param_value(item) for item in node.get('items', []))
        if isinstance(node, dict) and node.get('type') == 'CALL':
            name = node.get('name')
            args = [self.evaluate_param_value(item) for item in node.get('args', [])]
            kwargs = {k: self.evaluate_param_value(v) for k, v in (node.get('kwargs') or {}).items()}
            if name in {"NoScan", "RangeScan", "CenterScan", "ExplicitScan"}:
                return self._scan_object(name, args, kwargs)
        return self.evaluate(node)

    def start_proc(self, statements):
        """
        Execute a list of statements sequentially.
        """
        for stmt in statements:
            self.execute_statement(stmt)

    def execute_statement(self, stmt):
        """
        Execute a single statement based on its type.
        """
        # Check for abort signal
        if 'check_abort' in self.context:
            self.context['check_abort']()

        stype = stmt['type']
        self.logger.info("Executing statement type=%s", stype)

        def is_literal(node):
            if isinstance(node, (int, float, str)):
                return True
            if isinstance(node, tuple):
                return all(is_literal(v) for v in node)
            if isinstance(node, dict) and node.get('type') == 'TUPLE':
                return all(is_literal(v) for v in node.get('items', []))
            return False

        def coerce_param_value(dtype, value, name):
            if dtype is None:
                return value
            if dtype == 'int':
                if isinstance(value, bool) or not isinstance(value, int):
                    raise ValueError(f"param '{name}' expects int value")
                return value
            if dtype == 'float':
                if isinstance(value, bool) or not isinstance(value, (int, float)):
                    raise ValueError(f"param '{name}' expects float value")
                return float(value)
            if dtype == 'bool':
                if not isinstance(value, bool):
                    raise ValueError(f"param '{name}' expects bool value")
                return value
            if dtype == 'string':
                return str(value)
            if dtype == 'scannable':
                if not VirtualProcessor._is_scan_object(value):
                    raise ValueError(f"param '{name}' expects a scan object")
                return VirtualProcessor._coerce_scan_to_declared_type(value, self.param_defaults.get(name))
            if dtype in ('number', 'auto'):
                if isinstance(value, bool) or not isinstance(value, (int, float)):
                    raise ValueError(f"param '{name}' expects numeric value")
                return value
            return value
        
        if stype == 'PARAM':
            run_arguments = self.context.get('run_arguments') or {}
            if stmt['name'] in run_arguments:
                val = run_arguments[stmt['name']]
                self.logger.info("Using runtime override for param %s = %s", stmt['name'], val)
            else:
                val = self.evaluate_param_value(stmt['value']) if stmt.get('metadata') else self.evaluate(stmt['value'])
            default_val = self.evaluate_param_value(stmt['value']) if stmt.get('metadata') else self.evaluate(stmt['value'])
            self.param_defaults[stmt['name']] = default_val
            val = coerce_param_value(stmt.get('dtype'), val, stmt.get('name'))
            self.vars[stmt['name']] = val
            self.logger.info(f"Defined param {stmt['name']} = {val}")

        elif stype == 'DYN_PARAM':
            # Dynamic parameter: available to the script but not exposed to the UI schema.
            val = self.evaluate(stmt['value'])
            self.vars[stmt['name']] = val
            self.logger.info(f"Defined dynp {stmt['name']} = {val}")
            
        elif stype == 'SET':
            val = self.evaluate(stmt['value'])
            target_name = stmt['name']
            
            if target_name in self.vars:
                self.vars[target_name] = val
            else:
                path = target_name
                if '.' in path:
                    parts = path.split('.')
                    inst = parts[0]
                    param = '.'.join(parts[1:])
                    self.context['instruments'].set_parameter(inst, param, val)
                    self.logger.info(f"Set {path} = {val}")
                else:
                    self.context['instruments'].set_parameter(None, path, val)
                    self.logger.info(f"Set {path} = {val}")

        elif stype == 'ASSIGN':
            val = self.evaluate(stmt['value'])
            self.vars[stmt['name']] = val
            # self.logger.info(f"Assigned {stmt['name']} = {val}")

        elif stype == 'RUN':
            args = [self.evaluate(a) for a in stmt['args']]

            self.logger.info(f"Running Sequencer with args: {args}")

            if not args:
                raise ValueError("run() requires at least a sequencer/device name")

            # Convenience: allow run(<device>) to use script-level fpga_code from context.
            if len(args) == 1 and 'fpga_code' in self.context:
                args.append(self.context['fpga_code'])

            if len(args) < 2:
                raise ValueError("run() requires run(<device_name>, <fpga_code_or_path>)")

            try:
                data = self.context['instruments'].run_fpga(args[0], args[1])
            except InstrumentError as exc:
                self.logger.error("Device failure during run(%s): %s", args[0], exc)
                raise
            try:
                preview = repr(data)
                if len(preview) > 1000:
                    preview = preview[:1000] + "...<truncated>"
                self.logger.info(
                    "Raw run() payload received: type=%s preview=%s",
                    type(data).__name__,
                    preview,
                )
            except Exception:
                self.logger.info("Raw run() payload received (repr failed): type=%s", type(data).__name__)
            data = self._normalize_run_data(data)
            
            target = stmt.get('target')
            if target:
                self.vars[target] = data
                self.logger.info(f"Assigned data to {target}")

        elif stype == 'INIT_DATA':
            kwargs = {k: self.evaluate(v) for k, v in stmt['kwargs'].items()}
            
            if 'param' not in kwargs:
                raise Exception("init_data requires 'param' argument")
            
            params = self._normalize_axis_names(kwargs['param'], 'param', allow_placeholder=False)
            data_axes = None
            data_axes_effective = []
            if 'data' in kwargs:
                data_axes = self._normalize_axis_names(kwargs['data'], 'data', allow_placeholder=True)
                data_axes_effective = [name for name in data_axes if name != '_']
            
            num_data = kwargs.get('num_data', None)
            if num_data is not None:
                if not isinstance(num_data, (int, np.integer)):
                    raise Exception("init_data 'num_data' must be an integer")
                num_data = int(num_data)
                if num_data < -1:
                    raise Exception("init_data 'num_data' must be >= -1")
            if data_axes is not None:
                if num_data in (None, -1):
                    num_data = len(data_axes)
                elif num_data != len(data_axes):
                    raise Exception(
                        f"init_data mismatch: num_data={num_data} but data axes has {len(data_axes)} entries"
                    )
                
            self.data_schema = {
                'param_axes': params,
                'num_data': num_data,
                'data_axes': data_axes,
                'data_axes_effective': data_axes_effective
            }
            self.logger.info(f"Initialized data schema: {self.data_schema}")
            
            if 'init_data' in self.context:
                self.context['init_data'](self.data_schema)

        elif stype == 'SAVE':
            if self.data_schema is None:
                raise Exception("Cannot call save() before init_data()")
                
            kwargs = {k: self.evaluate(v) for k, v in stmt['kwargs'].items()}
            
            if 'params' not in kwargs or 'data' not in kwargs:
                raise Exception("save() requires 'params' and 'data' arguments")
            
            params = kwargs['params']
            data = kwargs['data']
            
            # Validate params
            if not isinstance(params, (list, tuple)):
                # Allow single value if schema expects 1 param
                if len(self.data_schema['param_axes']) == 1:
                    params = (params,)
                else:
                    raise Exception(f"save() 'params' must be a tuple matching {self.data_schema['param_axes']}")
            
            if len(params) != len(self.data_schema['param_axes']):
                raise Exception(f"Expected {len(self.data_schema['param_axes'])} params, got {len(params)}")
                
            data = self._normalize_save_data(data)
            num_rows = len(data)
            schema_rows = self.data_schema.get('num_data')
            if schema_rows in (None, -1):
                self.data_schema['num_data'] = num_rows
            elif num_rows != schema_rows:
                raise Exception(f"Expected data to have {schema_rows} row(s), got {num_rows}")
            schema_axes = self.data_schema.get('data_axes')
            if schema_axes is not None and len(schema_axes) != num_rows:
                raise Exception(
                    f"Expected data rows to match init_data(data=...) axes length {len(schema_axes)}, got {num_rows}"
                )
                
            # Validate data lengths
            vector_len = None
            for i, d in enumerate(data):
                if not isinstance(d, (list, tuple)):
                     raise Exception(f"Data row {i} is not a vector (list/tuple)")
                if vector_len is None:
                    vector_len = len(d)
                elif len(d) != vector_len:
                    raise Exception(f"Data vector lengths mismatch: {vector_len} vs {len(d)}")
            
            self.logger.info(f"Saving valid data block: params={params}, data_shape=({len(data)}, {vector_len})")
            
            if 'save_data' in self.context:
                self.context['save_data'](params, data)
            else:
                self.logger.info("WARNING: No save_data handler in context")

        elif stype == 'SLEEP':
            duration = self.evaluate(stmt['duration'])
            self.logger.info("Sleeping for %s seconds", duration)
            self.context['sleep'](duration)
            
        elif stype == 'FOR':
            var = stmt['var']
            run_arguments = self.context.get('run_arguments') or {}
            if stmt.get('iterable') is not None:
                iterable = self.evaluate(stmt['iterable'])
                if var in run_arguments:
                    iterable = run_arguments[var]
                    self.logger.info("Entering FOR loop var=%s using runtime scan override values=%s", var, iterable)
                else:
                    self.logger.info("Entering FOR loop var=%s iterable=%s", var, iterable)
                vals = self._scan_values(iterable)
            else:
                start = self.evaluate(stmt['start'])
                end = self.evaluate(stmt['end'])
                step = self.evaluate(stmt['step'])
                self.logger.info("Entering FOR loop var=%s start=%s end=%s step=%s", var, start, end, step)
                # Use a small epsilon to include the end value if it matches the step.
                vals = np.arange(start, end + step/1000.0, step)
            
            for val in vals:
                self.vars[var] = float(val)
                self.start_proc(stmt['body'])
            self.logger.info("Exiting FOR loop var=%s", var)

        elif stype == 'IF':
            condition = self.evaluate(stmt['condition'])
            self.logger.info("Evaluated IF condition=%s", condition)
            if condition:
                self.start_proc(stmt['true_body'])
            elif stmt['false_body']:
                self.start_proc(stmt['false_body'])
